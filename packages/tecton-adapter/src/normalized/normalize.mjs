// Normalizer: RawTectonSource -> NormalizedTectonTheme (see contract.ts).
// Every transformation is an explicit, asserted string operation so that an upstream change which
// invalidates an assumption fails the build instead of silently producing a wrong theme.

const EXPECTED_CORE_EXPORTS = [
  'ThemeManager',
  'borderRadius',
  'borderWidth',
  'cssVar',
  'fontFamilies',
  'iconSize',
  'injectTectonTokens',
  'spacing',
  'tectonPaletteDark',
  'tectonPaletteLight',
  'textStyles',
  'themeManager',
];

import { applyPatches } from './patches.mjs';

const REQUIRED_MUI_SOURCES = ['createMuiTheme.ts', 'components/index.ts', 'components/shared.ts'];

function assert(cond, message) {
  if (!cond) throw new Error(`[tecton-adapter] ${message}`);
}

function header(raw) {
  return (
    `/* AUTO-GENERATED by @tecton-mui/tecton-adapter from Tecton ${raw.version} (${raw.origin} source).\n` +
    ` * Do not edit by hand: run \`pnpm tecton:sync\` / \`pnpm --filter @tecton-mui/tecton-adapter emit\`. */\n`
  );
}

function splitRegions(coreModule) {
  const regions = {};
  for (const m of coreModule.matchAll(/\/\/#region ([^\n]+)\n([\s\S]*?)\/\/#endregion/g)) {
    regions[m[1].trim()] = m[2];
  }
  return regions;
}

function regionByName(regions, suffix) {
  const key = Object.keys(regions).find((k) => k.endsWith(suffix));
  assert(
    key,
    `tecton-core region "${suffix}" not found (found: ${Object.keys(regions).join(', ')})`,
  );
  return regions[key];
}

function normalizeCore(raw) {
  const exportLine = raw.coreModule.match(/export \{([^}]+)\};?\s*$/m);
  assert(exportLine, 'tecton-core export list not found');
  const exportsFound = exportLine[1]
    .split(',')
    .map((s) => s.trim())
    .filter(Boolean)
    .sort();
  assert(
    JSON.stringify(exportsFound) === JSON.stringify([...EXPECTED_CORE_EXPORTS].sort()),
    `tecton-core exports changed: ${exportsFound.join(', ')}`,
  );

  const regions = splitRegions(raw.coreModule);
  const tokensRegion = regionByName(regions, 'tokens.scss?raw');
  const tokensLiteral = tokensRegion.match(/var tokens_default = ("(?:[^"\\]|\\.)*");/);
  assert(tokensLiteral, 'tokens CSS string not found');
  const tokensCss = JSON.parse(tokensLiteral[1]);

  // Upstream evaluates `injectTectonTokens()` in its index module and constructs the shared
  // ThemeManager at import time. We drop the index side effect and make the shared manager lazy so
  // that importing the library never touches the DOM; hosts/ThemeProvider initialize explicitly.
  const indexRegion = regionByName(regions, 'src/index.ts');
  assert(
    indexRegion.trim() === 'injectTectonTokens();',
    'unexpected tecton-core index side effects',
  );

  let themeManager = regionByName(regions, 'theme-manager/ThemeManager.ts');
  const eager = /var themeManager = \/\* @__PURE__ \*\/ sharedThemeManager\(\);\n?/;
  assert(eager.test(themeManager), 'eager shared themeManager construction not found');
  themeManager = themeManager.replace(eager, '');
  themeManager = themeManager.replace(/^.*@__PURE__ tells the bundler.*\n/m, '');
  assert(/function sharedThemeManager\(\)/.test(themeManager), 'sharedThemeManager() not found');
  assert(
    themeManager.includes('__WEBFRAMEWORK_TECTON_THEME_MANAGER__'),
    'shared manager key changed',
  );

  const h = header(raw);
  const nocheck = '// @ts-nocheck -- verbatim upstream JavaScript; typed by ./index.ts\n';
  const modules = {
    'core/tokens.ts': `${h}const tokensCss: string = ${JSON.stringify(tokensCss)};\nexport default tokensCss;\n`,
    'core/injectTokens.ts':
      `${h}${nocheck}import tokens_default from './tokens.js';\n` +
      `${regionByName(regions, 'css/injectTokens.ts')}\nexport { TOKENS_MARKER, injectTectonTokens, cssVar };\n`,
    'core/ThemeManager.ts':
      `${h}${nocheck}import { injectTectonTokens } from './injectTokens.js';\n` +
      `${themeManager}\nexport { ThemeManager, sharedThemeManager, DEFAULT_STORAGE_KEY, DATA_ATTRIBUTE };\n`,
    'core/palette-light.ts': `${h}${regionByName(regions, 'palette-light.ts')}\nexport { tectonPaletteLight };\n`,
    'core/palette-dark.ts': `${h}${regionByName(regions, 'palette-dark.ts')}\nexport { tectonPaletteDark };\n`,
  };
  const scales = Object.entries(regions).find(([, body]) => /var spacing = \{/.test(body));
  assert(scales, 'scales region (spacing/borderRadius/borderWidth/iconSize) not found');
  modules['core/scales.ts'] =
    `${h}${scales[1]}\nexport { spacing, borderRadius, borderWidth, iconSize };\n`;
  modules['core/typography.ts'] =
    `${h}${regionByName(regions, 'typography.ts')}\nexport { fontFamilies, textStyles };\n`;
  // Typed facade over the verbatim (untyped) upstream JavaScript regions.
  modules['core/index.ts'] =
    `${h}import * as inject from './injectTokens.js';\n` +
    `import * as manager from './ThemeManager.js';\n\n` +
    `export type ThemeMode = 'light' | 'dark';\n` +
    `export type ThemeModePreference = ThemeMode | 'system';\n` +
    `export interface ThemeManagerState {\n  mode: ThemeMode;\n  preference: ThemeModePreference;\n}\n` +
    `export interface ThemeManagerConfig {\n  storageKey?: string;\n  defaultMode?: ThemeModePreference;\n}\n` +
    `export interface TectonThemeManager {\n` +
    `  configure(config: ThemeManagerConfig): void;\n  getMode(): ThemeMode;\n  getPreference(): ThemeModePreference;\n` +
    `  setMode(mode: ThemeModePreference): void;\n  setPreference(preference: ThemeModePreference): void;\n` +
    `  clearPreference(): void;\n  toggleMode(): void;\n` +
    `  subscribe(listener: (state: ThemeManagerState) => void): () => boolean;\n  destroy(): void;\n}\n` +
    `export type ThemeManagerConstructor = new (config?: ThemeManagerConfig) => TectonThemeManager;\n\n` +
    `export const cssVar = inject.cssVar as (name: string, fallback?: string) => string;\n` +
    `export const injectTectonTokens = inject.injectTectonTokens as () => void;\n` +
    `export const TOKENS_MARKER = inject.TOKENS_MARKER as string;\n` +
    `export const ThemeManager = manager.ThemeManager as ThemeManagerConstructor;\n` +
    `/** Returns the page-wide shared manager (created on first call, shared across bundles via globalThis). */\n` +
    `export const sharedThemeManager = manager.sharedThemeManager as () => TectonThemeManager;\n` +
    `export const DEFAULT_STORAGE_KEY = manager.DEFAULT_STORAGE_KEY as string;\n` +
    `export const DATA_ATTRIBUTE = manager.DATA_ATTRIBUTE as string;\n` +
    `export { tectonPaletteLight } from './palette-light.js';\n` +
    `export { tectonPaletteDark } from './palette-dark.js';\n` +
    `export { spacing, borderRadius, borderWidth, iconSize } from './scales.js';\n` +
    `export { fontFamilies, textStyles } from './typography.js';\n`;
  return { modules, tokensCss };
}

function rewriteImports(source, filePath) {
  const depth = filePath.split('/').length - 1;
  const coreRel = `${depth === 0 ? './' : '../'.repeat(depth)}../core/index.js`;
  return source
    .replace(/from "@webframework\/tecton-core"/g, `from "${coreRel}"`)
    .replace(/from "(\.\.?\/[^"]+)"/g, (m, spec) => {
      if (spec.endsWith('.js')) return m;
      const target = spec === './components' ? './components/index' : spec;
      return `from "${target}.js"`;
    });
}

function normalizeMui(raw) {
  for (const required of REQUIRED_MUI_SOURCES) {
    assert(raw.muiSources[required], `tecton-mui source ${required} missing`);
  }
  assert(
    /export function createMuiTheme\(options: CreateMuiThemeOptions = \{\}\): Theme/.test(
      raw.muiSources['createMuiTheme.ts'],
    ),
    'createMuiTheme signature changed',
  );
  const h = header(raw);
  const modules = {};
  for (const [path, source] of Object.entries(raw.muiSources)) {
    const foreign = source.match(
      /from "(?!react"|@mui\/material|\.|@webframework\/tecton-core")([^"]+)"/,
    );
    assert(!foreign, `${path} imports an unsupported module: ${foreign?.[1]}`);
    modules[`mui/${path}`] = `${h}${rewriteImports(source, path)}`;
  }
  return applyPatches(modules, 'mui/');
}

function tokenNames(tokensCss) {
  return [
    ...new Set([...tokensCss.matchAll(/--tecton-([a-z0-9-]+)\s*:/g)].map((m) => m[1])),
  ].sort();
}

function normalizeIcons(iconsCss) {
  const classes = [
    ...new Set(
      [...iconsCss.matchAll(/^\.tecton-([a-z0-9-]+)\s*\{\s*--tecton-icon-url:/gm)].map((m) => m[1]),
    ),
  ].sort();
  assert(classes.length > 0, 'no icon declarations found in icons.css');
  const byName = new Map();
  for (const cls of classes) {
    const m = cls.match(/^(.*)-(outline|filled)$/);
    const name = m ? m[1] : cls;
    const entry = byName.get(name) ?? { name, variants: [], multicolor: !m };
    if (m) entry.variants.push(m[2]);
    byName.set(name, entry);
  }
  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function validate({ tokensCss, tokens, icons, mui, iconsCss }) {
  assert(/:root,\s*\[data-theme="light"\]/.test(tokensCss), 'light/:root token block missing');
  assert(/\[data-theme="dark"\]/.test(tokensCss), 'dark token block missing');
  const tokenSet = new Set(tokens);
  // Component-scoped custom properties the theme itself declares (e.g. "--tecton-appbar-product-color").
  for (const source of Object.values(mui)) {
    for (const m of source.matchAll(/["'`]--tecton-([a-z0-9-]+)["'`]\s*:/g)) tokenSet.add(m[1]);
  }
  const missing = new Set();
  for (const [path, source] of Object.entries(mui)) {
    for (const m of source.matchAll(/cssVar\(\s*["'`]([a-z0-9-]+)["'`]/g)) {
      if (!tokenSet.has(m[1])) missing.add(`${m[1]} (${path})`);
    }
  }
  assert(missing.size === 0, `theme references undefined tokens: ${[...missing].join(', ')}`);
  const iconClasses = new Set(iconsCss.match(/\.tecton-[a-z0-9-]+/g).map((c) => c.slice(1)));
  for (const [path, source] of Object.entries(mui)) {
    for (const m of source.matchAll(/["'`](tecton-[a-z0-9-]+-(?:outline|filled))["'`]/g)) {
      assert(iconClasses.has(m[1]), `${path} references missing icon class ${m[1]}`);
    }
  }
  assert(
    icons.some((i) => i.name === 'add'),
    'expected core icon "add" missing',
  );
}

/** @returns {import('./contract.ts').NormalizedTectonTheme} */
export function normalize(raw) {
  const core = normalizeCore(raw);
  const mui = normalizeMui(raw);
  const tokens = tokenNames(core.tokensCss);
  const icons = normalizeIcons(raw.iconsCss);
  validate({ tokensCss: core.tokensCss, tokens, icons, mui, iconsCss: raw.iconsCss });

  const h = header(raw);
  const mono = icons.filter((i) => !i.multicolor);
  const multi = icons.filter((i) => i.multicolor);
  const union = (list) => (list.length ? list.map((i) => `  | '${i.name}'`).join('\n') : '  never');
  const modules = {
    ...core.modules,
    ...mui,
    'icons.ts':
      `${h}/** Monochrome Tecton icons (tinted with currentColor). */\nexport type TectonMonochromeIconName =\n${union(mono)};\n\n` +
      `/** Multicolor Tecton icons (logos/symbols; fixed colors, no variants). */\nexport type TectonMulticolorIconName =\n${union(multi)};\n\n` +
      `export type TectonIconName = TectonMonochromeIconName | TectonMulticolorIconName;\n\n` +
      `/** Available variants per monochrome icon; multicolor icons map to an empty list. */\n` +
      `export const tectonIconVariants: Readonly<Record<TectonIconName, readonly ('outline' | 'filled')[]>> = {\n` +
      icons
        .map((i) => `  '${i.name}': [${i.variants.map((v) => `'${v}'`).join(', ')}],`)
        .join('\n') +
      `\n};\n`,
    'meta.ts':
      `${h}export const TECTON_VERSION = '${raw.version}';\nexport const TECTON_SOURCE = '${raw.origin}';\n` +
      `export const TECTON_MODES = ['light', 'dark'] as const;\nexport const TECTON_TOKEN_COUNT = ${tokens.length};\n`,
  };

  const cssHeader = `/* Tecton ${raw.version} (${raw.origin} source) - emitted by @tecton-mui/tecton-adapter. Do not edit. */\n`;
  const assets = {
    'tokens.css': cssHeader + core.tokensCss,
    'fonts.css': cssHeader + raw.fontsCss,
    'icons.css': cssHeader + raw.iconsCss,
    ...raw.fonts,
    'provenance.json':
      JSON.stringify(
        { version: raw.version, origin: raw.origin, artifacts: raw.provenance },
        null,
        2,
      ) + '\n',
  };

  return {
    version: raw.version,
    origin: raw.origin,
    modes: ['light', 'dark'],
    tokensCss: core.tokensCss,
    tokenNames: tokens,
    icons,
    modules,
    assets,
  };
}
